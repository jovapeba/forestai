/** "Brown Bear (Ursus arctos)" → { commonName: 'Brown Bear', latin: 'Ursus arctos' } */
export function parseSpecies(label: string): { commonName: string; latin: string } {
  const m = label.match(/^(.*?)\s*\((.+)\)\s*$/);
  return m ? { commonName: m[1], latin: m[2] } : { commonName: label, latin: label };
}
