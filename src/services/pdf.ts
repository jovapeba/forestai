/* ------------------------ minimal valid PDF builder ---------------------- */

function asciiOnly(s: string): string {
  const map: Record<string, string> = {
    'š': 's', 'Š': 'S', 'č': 'c', 'Č': 'C', 'ž': 'z', 'Ž': 'Z', 'đ': 'd', 'Đ': 'D',
    'ć': 'c', 'Ć': 'C', 'ä': 'ae', 'ö': 'oe', 'ü': 'ue', 'ß': 'ss', 'é': 'e', 'è': 'e',
    'ó': 'o', 'á': 'a', 'í': 'i', 'ú': 'u', 'ñ': 'n', 'ł': 'l', '°': ' deg',
  };
  return s
    .replace(/[ščžđćäöüßéèóáíúñł°]/g, (c) => map[c] ?? '?')
    .replace(/[^\x20-\x7E]/g, '')
    .slice(0, 96);
}

function esc(s: string): string {
  return asciiOnly(s).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

export function generateBriefingPdf(title: string, lines: string[]): Blob {
  const contentParts: string[] = ['BT', '/F2 15 Tf', '52 792 Td', `(${esc(title)}) Tj`, '/F1 9 Tf', '0 -26 Td', '12.5 TL'];
  for (const line of lines) contentParts.push(`(${esc(line)}) Tj T*`);
  contentParts.push('ET');
  const stream = contentParts.join('\n');

  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objs.forEach((body, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((o) => {
    pdf += `${String(o).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
}
